#!/usr/bin/env python3
"""Write a simulation model of the ECP5 DP16KD block RAM for gate-level
runs.

usage: ecp5_bram_sim.py OUT_V

Yosys ships DP16KD as a black box. This model covers what Yosys's own
mapping (its ecp5/brams_map.v and brams.txt) produces: both ports in
widths 1, 2, 4, 9 and 18, unregistered outputs, the three write modes,
byte enables on the 18-bit width, and the initial contents. The
storage is 1,024 words of 18 bits; a 9-bit port sees each word as two
halves, and the narrower widths use eight bits of each half, as Yosys
lays its data out.
"""
import sys

PORT = '''
    // ---- port {p} ----
    wire [13:0] ad{l} = {{{ad}}};
    wire [17:0] di{l} = {{{di}}};
    reg  [17:0] do{l} = 18'd0;
    assign {{{do}}} = do{l};
    wire        clk{l} = (CLK{p}MUX == "INV") ? !CLK{p} : CLK{p};
    wire [9:0]  w{l} = ad{l}[13:4];
    // Where in the word this port's data sits, and its mask.
    wire [4:0]  sh{l} = (DATA_WIDTH_{p} == 18) ? 5'd0 :
                       (DATA_WIDTH_{p} == 9)  ? (ad{l}[3] ? 5'd9 : 5'd0) :
                       (DATA_WIDTH_{p} == 4)  ? (ad{l}[3] ? 5'd9 : 5'd0) + {{2'd0, ad{l}[2], 2'd0}} :
                       (DATA_WIDTH_{p} == 2)  ? (ad{l}[3] ? 5'd9 : 5'd0) + {{2'd0, ad{l}[2:1], 1'd0}} :
                                               (ad{l}[3] ? 5'd9 : 5'd0) + {{2'd0, ad{l}[2:0]}};
    wire [17:0] m{l}  = (DATA_WIDTH_{p} == 18) ? {{{{9{{ad{l}[1]}}}}, {{9{{ad{l}[0]}}}}}} :
                       (DATA_WIDTH_{p} == 9)  ? 18'h001FF :
                       (DATA_WIDTH_{p} == 4)  ? 18'h0000F :
                       (DATA_WIDTH_{p} == 2)  ? 18'h00003 : 18'h00001;
    wire [17:0] rm{l} = (DATA_WIDTH_{p} == 18) ? 18'h3FFFF : m{l};
    wire [17:0] old{l} = mem[w{l}];
    wire [17:0] new{l} = (old{l} & ~(m{l} << sh{l})) | ((di{l} & m{l}) << sh{l});
    always @(posedge clk{l}) begin
        if (CE{p}) begin
            if (WE{p}) begin
                mem[w{l}] <= new{l};
                if (WRITEMODE_{p} == "WRITETHROUGH")
                    do{l} <= (new{l} >> sh{l}) & rm{l};
                else if (WRITEMODE_{p} == "READBEFOREWRITE")
                    do{l} <= (old{l} >> sh{l}) & rm{l};
            end else
                do{l} <= (old{l} >> sh{l}) & rm{l};
        end
        if (RST{p})
            do{l} <= 18'd0;
    end
'''


def bits(prefix, n):
    return ', '.join('%s%d' % (prefix, i) for i in range(n - 1, -1, -1))


def main():
    out = ['// Generated by tools/ecp5_bram_sim.py: a simulation model, not for synthesis.',
           'module DP16KD(',
           '    input ' + bits('DIA', 18) + ',',
           '    input ' + bits('ADA', 14) + ',',
           '    input CEA, OCEA, CLKA, WEA, RSTA, CSA2, CSA1, CSA0,',
           '    output ' + bits('DOA', 18) + ',',
           '    input ' + bits('DIB', 18) + ',',
           '    input ' + bits('ADB', 14) + ',',
           '    input CEB, OCEB, CLKB, WEB, RSTB, CSB2, CSB1, CSB0,',
           '    output ' + bits('DOB', 18),
           ');',
           '    parameter DATA_WIDTH_A = 18;',
           '    parameter DATA_WIDTH_B = 18;',
           '    parameter REGMODE_A = "NOREG";',
           '    parameter REGMODE_B = "NOREG";',
           '    parameter RESETMODE = "SYNC";',
           '    parameter ASYNC_RESET_RELEASE = "SYNC";',
           '    parameter CSDECODE_A = "0b000";',
           '    parameter CSDECODE_B = "0b000";',
           '    parameter WRITEMODE_A = "NORMAL";',
           '    parameter WRITEMODE_B = "NORMAL";',
           '    parameter CLKAMUX = "CLKA";',
           '    parameter CLKBMUX = "CLKB";',
           '    parameter GSR = "ENABLED";',
           '    parameter INIT_DATA = "STATIC";']
    for i in range(64):
        out.append("    parameter [319:0] INITVAL_%02X = 320'd0;" % i)
    out.append('')
    out.append('    reg [17:0] mem [0:1023];')
    out.append('    integer i;')
    out.append('    initial begin')
    for i in range(64):
        out.append('        for (i = 0; i < 16; i = i + 1) '
                   'mem[%d + i] = INITVAL_%02X[i * 20 +: 18];' % (i * 16, i))
    out.append('    end')
    for p, l in (('A', 'a'), ('B', 'b')):
        out.append(PORT.format(p=p, l=l, ad=bits('AD' + p, 14),
                               di=bits('DI' + p, 18), do=bits('DO' + p, 18)))
    out.append('endmodule')
    open(sys.argv[1], 'w').write('\n'.join(out) + '\n')


if __name__ == '__main__':
    main()
